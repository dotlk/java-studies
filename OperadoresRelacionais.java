public class OperadoresRelacionais {
    
    public static void main(String[] args) {
        int a = 10;
        int b = 20;

        //Igual a
        System.out.println(a == b); //false

        //Diferente de
        System.out.println(a != b); //true

        //Maior que
        System.out.println(a > b); //false

        //Menor que
        System.out.println(a < b); //true

        //Maior ou igual a
        System.out.println(a >= b); //false

        //Menor ou igual a
        System.out.println(a <= b); //true
    }
}
