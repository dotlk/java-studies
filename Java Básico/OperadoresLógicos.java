public class OperadoresLógicos {
    
    public static void main(String[] args) {
        boolean x = true;
        boolean y = false;

        //Operador AND (&&)
        System.out.println(x && y); //false

        //Operador OR (||)
        System.out.println(x || y); //true

        //Operador NOT (!)
        System.out.println(!x); //false
        System.out.println(!y); //true
    }
}
