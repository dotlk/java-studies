public class LoopFor {
    
    public static void main(String[] args) {

        //A estrutura do for é composta por três partes: inicialização, condição e incremento.
        //A variável de controle (neste caso, i) é inicializada dentro da estrutura do loop for.

        //Imprimir os números de 1 a 10 usando um loop for
        for (int i = 1; i <= 10; i++) {
            System.out.println(i);
        }
    }        
}
