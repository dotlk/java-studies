public class OperadoresAritméticos {
    
    public static void main(String[] args) {
        //soma
        System.out.println(10+10);

        //subtração
        System.out.println(10-5);

        //multiplicação
        System.out.println(10*5);

        //divisão
        System.out.println(10/5);
        
        //módulo (resto da divisão)
        System.out.println(10%3);


    }
}
